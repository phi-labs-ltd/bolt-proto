package main

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"github.com/bufbuild/protoplugin"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
	"google.golang.org/protobuf/types/dynamicpb"
)

const (
	pairExtension     = "bolt.options.v1.pair"
	validateExtension = "bolt.options.v1.validate"
	outputFile        = "bolt_ext.rs"
	header            = "// @generated by bolt-proto-extensions from bolt.options.v1 options. DO NOT EDIT.\n"
)

func main() {
	protoplugin.Main(protoplugin.HandlerFunc(handle))
}

func handle(_ context.Context, _ protoplugin.PluginEnv, w protoplugin.ResponseWriter, req protoplugin.Request) error {
	w.SetFeatureProto3Optional()

	files, err := req.AllFiles()
	if err != nil {
		return err
	}
	targets, err := req.FileDescriptorsToGenerate()
	if err != nil {
		return err
	}

	var out strings.Builder
	out.WriteString(header)
	pairExt, err := findExtension(files, pairExtension)
	if err != nil {
		return err
	}
	validateExt, err := findExtension(files, validateExtension)
	if err != nil {
		return err
	}

	var errs []error
	for _, file := range targets {
		for _, message := range allMessages(file.Messages()) {
			code, err := renderMessage(message, pairExt, validateExt)
			if err != nil {
				errs = append(errs, fmt.Errorf("%s: %s: %w", file.Path(), message.FullName(), err))
				continue
			}
			out.WriteString(code)
		}
	}

	if err := errors.Join(errs...); err != nil {
		w.AddError(err.Error())
		return nil
	}
	w.AddFile(outputFile, out.String())
	return nil
}

// findExtension returns nil when the extension isn't in the request, e.g. when no
// target file imports bolt/options/v1/options.proto.
func findExtension(files *protoregistry.Files, name protoreflect.FullName) (protoreflect.ExtensionDescriptor, error) {
	desc, err := files.FindDescriptorByName(name)
	if err != nil {
		return nil, nil
	}
	ext, ok := desc.(protoreflect.ExtensionDescriptor)
	if !ok {
		return nil, fmt.Errorf("%s is a %T, not an extension", name, desc)
	}
	return ext, nil
}

func renderMessage(message protoreflect.MessageDescriptor, pairExt, validateExt protoreflect.ExtensionDescriptor) (string, error) {
	var code strings.Builder
	if pairExt != nil {
		spec, err := pairSpec(message, pairExt)
		if err != nil {
			return "", err
		}
		if spec != nil {
			pair, err := renderPair(message, spec)
			if err != nil {
				return "", err
			}
			code.WriteString(pair)
		}
	}
	if validateExt != nil {
		rules, err := validateRules(message, validateExt)
		if err != nil {
			return "", err
		}
		if len(rules) > 0 {
			validate, err := renderValidate(message, rules)
			if err != nil {
				return "", err
			}
			code.WriteString(validate)
		}
	}
	return code.String(), nil
}

func allMessages(messages protoreflect.MessageDescriptors) []protoreflect.MessageDescriptor {
	var all []protoreflect.MessageDescriptor
	for i := range messages.Len() {
		message := messages.Get(i)
		if message.IsMapEntry() {
			continue
		}
		all = append(all, message)
		all = append(all, allMessages(message.Messages())...)
	}
	return all
}

// extensionPayloads reads an extension straight off the options' wire bytes:
// whether it was decoded as a known extension or kept as unknown fields, it
// marshals the same. It returns one payload per length-delimited record, so a
// message extension may come back split and a repeated string comes back as one
// payload per value.
func extensionPayloads(options proto.Message, ext protoreflect.ExtensionDescriptor) ([][]byte, error) {
	raw, err := proto.Marshal(options)
	if err != nil {
		return nil, err
	}
	var payloads [][]byte
	for len(raw) > 0 {
		number, typ, n := protowire.ConsumeTag(raw)
		if n < 0 {
			return nil, protowire.ParseError(n)
		}
		raw = raw[n:]
		if number == ext.Number() && typ == protowire.BytesType {
			value, m := protowire.ConsumeBytes(raw)
			if m < 0 {
				return nil, protowire.ParseError(m)
			}
			payloads = append(payloads, value)
			raw = raw[m:]
			continue
		}
		m := protowire.ConsumeFieldValue(number, typ, raw)
		if m < 0 {
			return nil, protowire.ParseError(m)
		}
		raw = raw[m:]
	}
	return payloads, nil
}

func pairSpec(message protoreflect.MessageDescriptor, ext protoreflect.ExtensionDescriptor) (protoreflect.Message, error) {
	payloads, err := extensionPayloads(message.Options(), ext)
	if err != nil || len(payloads) == 0 {
		return nil, err
	}
	spec := dynamicpb.NewMessage(ext.Message())
	for _, payload := range payloads {
		if err := proto.Unmarshal(payload, spec); err != nil {
			return nil, err
		}
	}
	return spec, nil
}
